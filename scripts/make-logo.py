def _elements2(theme, S, uid):
    th = THEMES2[theme]
    r = S * 0.05
    sw = S * 0.078  # stroke weight of the monogram
    top, bot = S * 0.335, S * 0.655  # cap line and base line
    vw, mw, ds = (
        S * 0.26,
        S * 0.28,
        sw,
    )  # V width, M width (stroke centres), full-stop square
    vhalf = sw / 2 * 1.09  # half the V arm, measured across (the arm leans ~23 deg)
    gap, dgap = S * 0.03, S * 0.03
    total = vhalf + vw + vhalf + gap + sw + mw + gap + dgap + ds - gap
    x0 = (
        (S - total) / 2 + vhalf + S * 0.012
    )  # centre the whole "VM." group (the cut arms reach a bit left)
    m0 = x0 + vw + vhalf + gap + sw / 2
    mid = top + (bot - top) * 0.58
    up = sw * 1.5  # strokes run past the cap line; the clip cuts them flat
    v = f"M{x0 - sw * 0.2:.1f} {top - up:.1f} L{x0 + vw / 2:.1f} {bot:.1f} L{x0 + vw + sw * 0.2:.1f} {top - up:.1f}"
    m = (
        f"M{m0:.1f} {bot + sw:.1f} L{m0:.1f} {top:.1f} L{m0 + mw / 2:.1f} {mid:.1f} "
        f"L{m0 + mw:.1f} {top:.1f} L{m0 + mw:.1f} {bot + sw:.1f}"
    )
    dx = m0 + mw + sw / 2 + dgap  # the full stop: a square on the base line
    t_in, t_len, t_w = S * 0.07, S * 0.05, max(S / 256, 1)
    ticks = []
    for cx, cy, sx, sy in (
        (t_in, t_in, 1, 1),
        (S - t_in, t_in, -1, 1),
        (t_in, S - t_in, 1, -1),
        (S - t_in, S - t_in, -1, -1),
    ):
        ticks.append(
            f'<path d="M{cx:.1f} {cy + sy * t_len:.1f} L{cx:.1f} {cy:.1f} L{cx + sx * t_len:.1f} {cy:.1f}" '
            f'fill="none" stroke="{th["tick"]}" stroke-width="{t_w:.1f}"/>'
        )
    stroke = f'fill="none" stroke-width="{sw:.1f}" stroke-linejoin="miter" stroke-miterlimit="8" stroke-linecap="butt"'
    return [
        "<defs>",
        f'<linearGradient id="{uid}-bg" x1="0" y1="0" x2="0.4" y2="1"><stop offset="0" stop-color="{th["bg0"]}"/>'
        f'<stop offset="1" stop-color="{th["bg1"]}"/></linearGradient>',
        f'<radialGradient id="{uid}-glow"><stop offset="0" stop-color="{th["glow"]}" stop-opacity="{th["glow_a"]}"/>'
        f'<stop offset="1" stop-color="{th["glow"]}" stop-opacity="0"/></radialGradient>',
        f'<pattern id="{uid}-grid" width="{S / 16:.2f}" height="{S / 16:.2f}" patternUnits="userSpaceOnUse">'
        f'<path d="M{S / 16:.2f} 0H0V{S / 16:.2f}" fill="none" stroke="{th["grid"]}" stroke-opacity="{th["grid_a"]}" '
        f'stroke-width="{max(S / 512, 0.5):.2f}"/></pattern>',
        f'<radialGradient id="{uid}-fade" cx="0.5" cy="0.35" r="0.7"><stop offset="0" stop-color="#fff"/>'
        f'<stop offset="1" stop-color="#fff" stop-opacity="0"/></radialGradient>',
        f'<mask id="{uid}-m"><rect width="{S}" height="{S}" fill="url(#{uid}-fade)"/></mask>',
        f'<linearGradient id="{uid}-v" x1="0" y1="{top:.1f}" x2="0" y2="{bot:.1f}" gradientUnits="userSpaceOnUse">'
        f'<stop offset="0" stop-color="{th["v0"]}"/>'
        f'<stop offset="1" stop-color="{th["v1"]}"/></linearGradient>',
        f'<linearGradient id="{uid}-mg" x1="0" y1="{top:.1f}" x2="0" y2="{bot:.1f}" gradientUnits="userSpaceOnUse">'
        f'<stop offset="0" stop-color="{th["m0"]}"/><stop offset="1" stop-color="{th["m1"]}"/></linearGradient>',
        f'<filter id="{uid}-blur" x="-50%" y="-50%" width="200%" height="200%"><feGaussianBlur stdDeviation="{S / 36:.1f}"/></filter>',
        f'<clipPath id="{uid}-clip"><rect width="{S}" height="{S}" rx="{r:.1f}"/></clipPath>',
        f'<clipPath id="{uid}-cap"><rect x="0" y="{top:.1f}" width="{S}" height="{S - top:.1f}"/></clipPath>',
        "</defs>",
        f'<g clip-path="url(#{uid}-clip)">',
        f'<rect width="{S}" height="{S}" fill="url(#{uid}-bg)"/>',
        f'<rect width="{S}" height="{S}" fill="url(#{uid}-grid)" mask="url(#{uid}-m)"/>',
        f'<ellipse cx="{S * 0.78:.1f}" cy="{S * 0.05:.1f}" rx="{S * 0.55:.1f}" ry="{S * 0.42:.1f}" fill="url(#{uid}-glow)"/>',
        *ticks,
        f'<g clip-path="url(#{uid}-cap)">',
        f'<path d="{m}" {stroke} stroke="{th["glow"]}" stroke-opacity="{th["glow_a"] * 1.6:.2f}" filter="url(#{uid}-blur)"/>',
        f'<path d="{v}" {stroke} stroke="url(#{uid}-v)"/>',
        f'<path d="{m}" {stroke} stroke="url(#{uid}-mg)"/>',
        "</g>",
        f'<rect x="{dx:.1f}" y="{bot - ds:.1f}" width="{ds:.1f}" height="{ds:.1f}" fill="{th["dot"]}"/>',
        f'<rect y="{S - S * 0.014:.1f}" width="{S}" height="{S * 0.014:.1f}" fill="{th["bar"]}" fill-opacity="0.9"/>',
        "</g>",
        f'<rect x="0.5" y="0.5" width="{S - 1}" height="{S - 1}" rx="{r - 0.5:.1f}" fill="none" stroke="{th["rim"]}"/>',
    ]


def mark(theme, size=512, uid=None, version="v2"):
    """The logo's elements without the <svg> wrapper, for embedding (ids prefixed by uid).
    v1 = _elements (circuit mark), v2 = _elements2 (geometric monogram, above)."""
    parts = {"v1": _elements, "v2": _elements2}
    if version not in parts:
        raise ValueError(f"unknown logo version {version!r}; use v1 or v2")
    return "\n".join(parts[version](theme, size, uid or f"vm-logo-{version}-{theme}"))


def logo2(theme, size=512):
    return (
        "\n".join(
            [
                HEAD2,
                f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {size} {size}" width="{size}" height="{size}" '
                f'role="img" aria-label="VM, Velimir Müller"><title>Velimir Müller</title>',
                *_elements2(theme, size, f"vm-logo2-{theme}"),
                "</svg>",
            ]
        )
        + "\n"
    )


def main():
    import argparse

    ap = argparse.ArgumentParser()
    ap.add_argument("--version", default="v2", choices=["v1", "v2"])
    opt = ap.parse_args()
    make = logo if opt.version == "v1" else logo2
    for theme in THEMES:
        path = os.path.join(
            ROOT, "assets", "logo", f"vm-logo-{opt.version}-{theme}.svg"
        )
        with open(path, "w", encoding="utf-8") as f:
            f.write(make(theme))
        print(path)


if __name__ == "__main__":
    main()
